#!/usr/bin/env python3
"""Build self-hosted UI font subsets: python -m pip install 'fonttools[woff]==4.25.0'.

The complete original font stays as the reproducible source. All its Unicode
characters are retained across disjoint CSS ranges, including user-entered text.
Generated derivatives use a new internal family name to respect the OFL's RFN.
Run from any directory; normal application builds do not require Python.
"""
import hashlib
import io
import json
from pathlib import Path

from fontTools import subset, version
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/fonts/PretendardVariable.woff2"
OUT = ROOT / "public/fonts/ui"
CSS = ROOT / "src/app/ui-font.css"
FAMILY = "SceneLog Sans"


def unicode_ranges(points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def build():
    raw = SOURCE.read_bytes()
    original = TTFont(io.BytesIO(raw))
    covered = set(original.getBestCmap())
    # UI copy plus Latin, combining marks and Korean Jamo stay together. New UI
    # copy still works without regeneration: it falls into the remaining ranges.
    common = {c for c in covered if c < 0x370 or 0x1100 <= c <= 0x11FF or 0x3130 <= c <= 0x318F}
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix in (".ts", ".tsx"):
            common.update(ord(c) for c in path.read_text() if ord(c) in covered)
    remaining = sorted(covered - common)
    groups = [("core", common)] + [(f"extra-{i // 256:02d}", set(remaining[i:i + 256])) for i in range(0, len(remaining), 256)]
    OUT.mkdir(parents=True, exist_ok=True)
    rules = ["/* Generated by scripts/subset-ui-font.py. OFL: /fonts/OFL.txt. */"]
    manifest = {"sourceSha256": hashlib.sha256(raw).hexdigest(), "sourceBytes": len(raw), "fontToolsVersion": version,
                "family": FAMILY, "codepoints": len(covered), "subsets": []}
    union = set()
    for label, points in groups:
        font = TTFont(io.BytesIO(raw), recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        for name in font["name"].names:
            replacements = {1: FAMILY, 3: "SceneLogSans-Subset-1", 4: FAMILY, 6: "SceneLogSans-Regular", 16: FAMILY, 25: "SceneLogSans"}
            if name.nameID in replacements:
                name.string = replacements[name.nameID].encode(name.getEncoding())
        font.flavor = "woff2"
        buffer = io.BytesIO()
        font.save(buffer)
        data = buffer.getvalue()
        filename = f"{label}-{hashlib.sha256(data).hexdigest()[:12]}.woff2"
        (OUT / filename).write_bytes(data)
        # Verify saved output, not just the pre-serialization font object.
        saved = TTFont(io.BytesIO(data))
        assert points <= set(saved.getBestCmap()), f"Missing characters in {label}"
        assert [(a.axisTag, a.minValue, a.maxValue) for a in saved["fvar"].axes] == [(a.axisTag, a.minValue, a.maxValue) for a in original["fvar"].axes]
        assert not union.intersection(points)
        union.update(points)
        ranges = unicode_ranges(points)
        rules.append(f'@font-face {{ font-family:"{FAMILY}"; src:url("/fonts/ui/{filename}") format("woff2"); font-weight:100 900; font-style:normal; font-display:swap; unicode-range:{ranges}; }}')
        manifest["subsets"].append({"file": filename, "bytes": len(data), "unicodeRange": ranges, "codepoints": len(points)})
    assert union == covered
    CSS.write_text("\n".join(rules) + "\n")
    (OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    # Only remove obsolete files generated in this dedicated output directory.
    current = {entry["file"] for entry in manifest["subsets"]}
    for path in OUT.glob("*.woff2"):
        if path.name not in current:
            path.unlink()
    print(json.dumps({"sourceBytes": len(raw), "coreBytes": manifest["subsets"][0]["bytes"], "subsets": len(groups), "preservedCodepoints": len(union)}))


if __name__ == "__main__":
    build()
